/**
 * What a tool call is allowed to do.
 *
 * Each guard takes what the call is about to do and returns null to allow it, or the sentence
 * Claude Code should be told instead. Parsing the payload and phrasing the refusal belong to
 * `claude.mjs`, so a guard never depends on the hook protocol.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';

/** A whole-file read of this size lands tens of thousands of tokens in context at once. */
const MAX_READ_BYTES = 120 * 1024;

/** Previews, not text: their size says nothing about what they cost in context. */
const PREVIEWED = /\.(png|jpe?g|gif|webp|pdf)$/i;

/**
 * Whether `origin/main` already carries the file. Git being unreachable answers no, which lets the
 * write through: the guard catches an accident, it does not hold a line.
 *
 * @param {string} path
 */
const isOnMain = (path) => {
  try {
    const absolute = resolve(path);
    const inRepo = ['-C', dirname(absolute)];
    const root = execFileSync('git', [...inRepo, 'rev-parse', '--show-toplevel'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    const tracked = relative(root, absolute).split(sep).join('/');
    execFileSync('git', [...inRepo, 'cat-file', '-e', `origin/main:${tracked}`], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};

const GENERATED = [
  {
    match: /routeTree\.gen\.ts$/,
    reason: 'routeTree.gen.ts is generated by TanStack Router. Do not edit it by hand.',
  },
  {
    match: /locales[/\\][^/\\]+[/\\]messages\.ts$/,
    reason: 'Compiled i18n files are generated. Edit the .po file and run yarn i18n:compile instead.',
  },
  {
    match: /back[/\\]trpc-procedures\.json$/,
    reason: 'trpc-procedures.json is generated from the tRPC routers. Run yarn workspace @app/back trpc:manifest instead of editing it.',
  },
  {
    match: /xtm-one[/\\]contract[/\\][^/\\]+\.json$/,
    reason: 'The XTM One contract pin is moved by Renovate. Run yarn xtm-one-contract --ref <commit> instead of editing it.',
  },
  {
    match: /db[/\\]migrations[/\\].+\.sql$/,
    // The migration a branch adds is only half generated: `yarn db:generate` never emits the
    // notify_data_changed triggers, and reconciling down to a single file rewrites its SQL. What
    // must never move is a migration already on origin/main, applied everywhere it has reached.
    permits: ({ path }) => !isOnMain(path),
    reason: 'This migration is already on origin/main and has been applied elsewhere. Change the schema and run yarn db:generate rather than editing it.',
  },
];

/**
 * @param {{ path: string, ranged: boolean }} call - `ranged` when the read asks for an offset or a
 *   limit, which bounds what it costs whatever the file weighs.
 */
export const guardRead = ({ path, ranged }) => {
  if (!path || ranged || PREVIEWED.test(path)) {
    return null;
  }
  let size;
  try {
    const stat = fs.statSync(path);
    if (!stat.isFile()) {
      return null;
    }
    size = stat.size;
  } catch {
    return null;
  }
  if (size <= MAX_READ_BYTES) {
    return null;
  }
  const kb = Math.round(size / 1024);
  const tokens = Math.round(size / 3000);
  return `Refused: ${path} is ${kb} KB (~${tokens}k tokens). Grep it with a pattern, or read the exact region with an offset and a limit.`;
};

/** @param {{ path: string }} call */
export const guardWrite = ({ path }) => {
  if (!path) {
    return null;
  }
  const hit = GENERATED.find((rule) => rule.match.test(path) && !rule.permits?.({ path }));
  return hit ? hit.reason : null;
};

/** Programs that put a whole file into context, as opposed to a bounded slice of it. */
const WHOLE_FILE_READER = /^\s*(?:cat|bat|type|Get-Content|gc)\s+(.*)$/;

/**
 * Downstream of one of these, only a bounded selection reaches the context. `sort`, `cut`, `jq`,
 * `sed` and `awk` are deliberately absent: they read every line and emit them all by default.
 */
const BOUNDING = /\b(?:head|tail|grep|rg|wc|Select-String|Select-Object)\b/;

/**
 * The size guard applies to the shell too, or it only protects the tool nobody is told to use:
 * one `cat` of a vendored dataset costs more context than a whole session of work.
 *
 * @param {{ command: string }} call
 */
export const guardBash = ({ command }) => {
  if (!command) {
    return null;
  }
  const [head, ...piped] = command.split('|');
  const reader = WHOLE_FILE_READER.exec(head);
  if (!reader || BOUNDING.test(piped.join('|'))) {
    return null;
  }
  for (const token of reader[1].split(/\s+/)) {
    if (!token || token.startsWith('-')) {
      continue;
    }
    const reason = guardRead({ path: token.replace(/^['"]|['"]$/g, ''), ranged: false });
    if (reason) {
      return reason;
    }
  }
  return null;
};
