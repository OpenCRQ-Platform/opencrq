/**
 * Generator for OpenCTI countries reference data.
 *
 * Source dataset (Apache-2.0): https://github.com/OpenCTI-Platform/datasets
 *   - data/geography.json: STIX 2.1 bundle of `location` objects (only Country locations are used).
 *
 * Download the file (pin a commit/tag for reproducibility), then run:
 *   npx tsx generate-countries.ts <path-to-geography.json>
 *
 * Generates ../data/countries-data.ts (canonical code = ISO alpha-3, no named ID constants).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { uuidv7 } from 'uuidv7';
import { countriesData } from '../data/countries-data';

interface StixObject {
  type: string,
  id: string,
  name?: string,
  x_opencti_location_type?: string,
  country?: string,
  x_opencti_aliases?: Array<string>,
}

interface StixBundle {
  objects: Array<StixObject>,
}

interface CountryRow {
  id: string,
  isoAlpha2: string,
  isoAlpha3: string,
  name: string,
}

// A country keeps the catalog id it was first minted with: tenant rows are derived from it.
const existingIds = new Map(countriesData.map((c) => [c.isoAlpha3, c.id]));

function escapeString(s: string): string {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
}

function parseCountries(objects: Array<StixObject>): Array<CountryRow> {
  const countries = objects.filter((o) => o.type === 'location' && o.x_opencti_location_type === 'Country');

  const rows: Array<CountryRow> = [];
  for (const c of countries) {
    const isoAlpha3 = (c.country ?? '').toUpperCase();
    if (!/^[A-Z]{3}$/.test(isoAlpha3)) {
      console.warn(`Skipping country "${c.name}" — missing/invalid ISO alpha-3 ("${c.country}")`);
      continue;
    }
    const isoAlpha2 = (c.x_opencti_aliases ?? []).map((a) => a.toUpperCase()).find((a) => /^[A-Z]{2}$/.test(a)) ?? '';
    rows.push({ id: existingIds.get(isoAlpha3) ?? uuidv7(), isoAlpha2, isoAlpha3, name: c.name ?? '' });
  }

  return rows.sort((a, b) => a.isoAlpha3.localeCompare(b.isoAlpha3));
}

function writeCountries(outputDir: string, rows: Array<CountryRow>): void {
  const lines = [
    '// Auto-generated by generate-countries.ts — DO NOT EDIT',
    '// Source: https://github.com/OpenCTI-Platform/datasets (data/geography.json, Apache-2.0)',
    '',
    'export interface CountryData {',
    '  id: string,',
    '  isoAlpha2: string,',
    '  isoAlpha3: string,',
    '  name: string,',
    '}',
    '',
    'export const countriesData: Array<CountryData> = [',
    ...rows.map((r) => [
      '  {',
      `    id: '${r.id}',`,
      `    isoAlpha2: '${escapeString(r.isoAlpha2)}',`,
      `    isoAlpha3: '${escapeString(r.isoAlpha3)}',`,
      `    name: '${escapeString(r.name)}',`,
      '  },',
    ].join('\n')),
    '];',
    '',
  ];
  writeFileSync(resolve(outputDir, 'countries-data.ts'), lines.join('\n'));
  console.log(`Written: countries-data.ts (${rows.length} countries)`);
}

function main(): void {
  const args = process.argv.slice(2);
  if (args.length < 1) {
    console.error('Usage: npx tsx generate-countries.ts <path-to-geography.json>');
    process.exit(1);
  }

  const geographyPath = args[0];
  const outputDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'data');

  console.log(`Reading geography from ${resolve(geographyPath)}...`);
  const bundle: StixBundle = JSON.parse(readFileSync(resolve(geographyPath), 'utf-8'));
  const countries = parseCountries(bundle.objects);
  writeCountries(outputDir, countries);

  console.log(`\nDone! Countries: ${countries.length}`);
}

main();
