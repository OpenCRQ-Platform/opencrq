/**
 * Generator for OpenCTI sectors reference data.
 *
 * Source dataset (Apache-2.0): https://github.com/OpenCTI-Platform/datasets
 *   - data/sectors.json: STIX 2.1 bundle of `identity` objects (identity_class="class").
 *
 * Download the file (pin a commit/tag for reproducibility), then run:
 *   npx tsx generate-sectors.ts <path-to-sectors.json>
 *
 * Generates ../data/sectors-data.ts. Only top-level sectors are emitted (a sector that is `part-of`
 * another sector is a sub-sector and is dropped, so only one sector level is emitted).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { uuidv7 } from 'uuidv7';
import { sectorsData } from '../data/sectors-data';

interface StixObject {
  type: string,
  id: string,
  name?: string,
  description?: string,
  identity_class?: string,
  relationship_type?: string,
  source_ref?: string,
  target_ref?: string,
}

interface StixBundle {
  objects: Array<StixObject>,
}

interface SectorRow {
  id: string,
  name: string,
  description: string | null,
}

// A sector keeps the catalog id it was first minted with: tenant rows are derived from it.
const existingIds = new Map(sectorsData.map((s) => [s.name, s.id]));

function escapeString(s: string): string {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
}

function quoteOrNull(s: string | null): string {
  return s === null ? 'null' : `'${escapeString(s)}'`;
}

function parseSectors(objects: Array<StixObject>): Array<SectorRow> {
  const classes = objects.filter((o) => o.type === 'identity' && o.identity_class === 'class');
  const classIds = new Set(classes.map((o) => o.id));

  const subSectorIds = new Set<string>();
  for (const o of objects) {
    if (o.type === 'relationship' && o.relationship_type === 'part-of' && o.source_ref && o.target_ref && classIds.has(o.target_ref)) {
      subSectorIds.add(o.source_ref);
    }
  }

  return classes
    .filter((s) => !subSectorIds.has(s.id))
    .map((s) => ({ id: existingIds.get(s.name ?? '') ?? uuidv7(), name: s.name ?? '', description: s.description ?? null }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function writeSectors(outputDir: string, rows: Array<SectorRow>): void {
  const lines = [
    '// Auto-generated by generate-sectors.ts — DO NOT EDIT',
    '// Source: https://github.com/OpenCTI-Platform/datasets (data/sectors.json, Apache-2.0)',
    '',
    'export interface SectorData {',
    '  id: string,',
    '  name: string,',
    '  description: string | null,',
    '}',
    '',
    'export const sectorsData: Array<SectorData> = [',
    ...rows.map((r) => [
      '  {',
      `    id: '${r.id}',`,
      `    name: '${escapeString(r.name)}',`,
      `    description: ${quoteOrNull(r.description)},`,
      '  },',
    ].join('\n')),
    '];',
    '',
  ];
  writeFileSync(resolve(outputDir, 'sectors-data.ts'), lines.join('\n'));
  console.log(`Written: sectors-data.ts (${rows.length} sectors)`);
}

function main(): void {
  const args = process.argv.slice(2);
  if (args.length < 1) {
    console.error('Usage: npx tsx generate-sectors.ts <path-to-sectors.json>');
    process.exit(1);
  }

  const sectorsPath = args[0];
  const outputDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'data');

  console.log(`Reading sectors from ${resolve(sectorsPath)}...`);
  const bundle: StixBundle = JSON.parse(readFileSync(resolve(sectorsPath), 'utf-8'));
  const sectors = parseSectors(bundle.objects);
  writeSectors(outputDir, sectors);

  console.log(`\nDone! Sectors: ${sectors.length}`);
}

main();
