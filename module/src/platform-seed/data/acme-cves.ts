const daysAgo = (now: Date, days: number): Date => new Date(now.getTime() - days * 86_400_000);

// CISA gives roughly three weeks from the listing, so the oldest entries are long past their date
// and the freshest are not due yet: both readings of the banner are visible in the demo tenant.
const KEV_DUE_DAYS = 21;

// The catalogue's own wording, one of the few boilerplates it cycles through.
const KEV_REQUIRED_ACTION = 'Apply updates per vendor instructions or discontinue use of the product if mitigations are unavailable.';

const kevNotes = (cveId: string): string =>
  `https://nvd.nist.gov/vuln/detail/${cveId} ; https://www.cisa.gov/known-exploited-vulnerabilities-catalog`;

const nvdReference = (cveId: string): AcmeCveReference => ({
  url: `https://nvd.nist.gov/vuln/detail/${cveId}`,
  source: 'nvd@nist.gov',
});

export const buildAcmeCveRows = (now: Date): Array<typeof cve.$inferInsert> =>
  ACME_CVE_SPECS.map((spec) => ({
    id: spec.id,
    tenantId: Tenant_Acme,
    cveId: spec.cveId,
    cvss: spec.cvss,
    cvssVector: spec.cvssVector,
    cvssUpdatedAt: daysAgo(now, Math.min(spec.createdDaysAgo, 30)),
    cwe: spec.cwe,
    epss: spec.epss,
    epssUpdatedAt: daysAgo(now, 3),
    kev: spec.kev,
    kevUpdatedAt: spec.kev ? daysAgo(now, Math.min(spec.createdDaysAgo, 14)) : null,
    kevRequiredAction: spec.kev ? KEV_REQUIRED_ACTION : null,
    kevDueDate: spec.kev ? daysAgo(now, spec.createdDaysAgo - KEV_DUE_DAYS) : null,
    kevNotes: spec.kev ? kevNotes(spec.cveId) : null,
    kevRansomwareUse: spec.kev ? (spec.ransomware ? 'Known' : 'Unknown') : null,
    vendorSolution: spec.vendorSolution ?? null,
    cveTitle: spec.cveTitle,
    cveDescription: spec.cveDescription,
    createdAt: daysAgo(now, spec.createdDaysAgo),
    updatedAt: daysAgo(now, 3),
  }));

/**
 * Every CVE points at its NVD record, and the ones whose advisory is known point at that too. The
 * NVD row carries no tag on purpose: an unanalysed record is the common case in the live feed, and
 * the surfaces have to read as well without tags as with them.
 */
export const buildAcmeCveReferenceRows = (): Array<typeof cveReferences.$inferInsert> =>
  ACME_CVE_SPECS.flatMap((spec, specIndex) =>
    [nvdReference(spec.cveId), ...(spec.references ?? [])].map((reference, referenceIndex) => ({
      id: cveReferenceId(specIndex, referenceIndex),
      tenantId: Tenant_Acme,
      cveId: spec.id,
      url: reference.url,
      source: reference.source,
      tags: reference.tags ?? null,
    })));

export const buildAcmeCveAffectedVersionRows = (): Array<typeof cveAffectedVersions.$inferInsert> =>
  ACME_CVE_SPECS.flatMap((spec, specIndex) =>
    (spec.fixes ?? []).map((fix, fixIndex) => ({
      id: cveAffectedVersionId(specIndex, fixIndex),
      tenantId: Tenant_Acme,
      cveId: spec.id,
      vendor: fix.vendor,
      product: fix.product,
      affectedFrom: fix.affectedFrom,
      affectedUpTo: fix.affectedUpTo,
      affectedUpToIncluded: fix.affectedUpToIncluded ?? false,
    })));
