/* eslint-disable no-console */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { parse } from 'postcss';

const PREFIX = '--fds-';

/**
 * Namespaces left untouched:
 * - `--fds-`: the design system's own prefix, double prefixing would break the class
 *   selectors that embed those names.
 * - `--radix-`: injected at runtime by Radix on the element itself, never declared here.
 * - `--tw-`: Tailwind's internal slots, where one utility deposits a fragment and another
 *   assembles it. Renaming them severs composition across the two builds: a `text-sm` from
 *   this stylesheet would read its line height from a slot the host's `leading-*` never
 *   writes, silently. Sound only while both builds know the same slots, hence
 *   `assertInterchangeableSlots`.
 */
const PRESERVED_NAMESPACES = [PREFIX, '--radix-', '--tw-'];

const VAR_REFERENCE = /var\(\s*(--[\w-]+)/g;

const prefixName = (name: string): string =>
  (PRESERVED_NAMESPACES.some((namespace) => name.startsWith(namespace))
    ? name
    : `${PREFIX}${name.slice(2)}`);

const prefixReferences = (value: string): string =>
  value.replace(VAR_REFERENCE, (match, name: string) => match.replace(name, prefixName(name)));

const HEADER = `/*
 * Generated by \`yarn fds:css\` from the pinned @filigran/design-system build.
 * Design system tokens are namespaced with \`--fds-\` so they coexist with the
 * @filigran/ui tokens that share their names but not their format. Tailwind's own
 * \`--tw-\` slots keep their names so effects still compose with the host build.
 * Class selectors are untouched: the design system JS bundle hardcodes those strings.
 * Do not edit by hand, rerun the script after bumping the design system.
 */
`;

const TAILWIND_BANNER = /tailwindcss v([\d.]+)/;

const TAILWIND_SLOT = /--tw-[a-z0-9-]+/g;

const readVersion = (packageJsonPath: string): string | undefined => {
  const manifest: unknown = JSON.parse(readFileSync(packageJsonPath, 'utf-8'));
  if (typeof manifest === 'object' && manifest !== null && 'version' in manifest
    && typeof manifest.version === 'string') {
    return manifest.version;
  }
  return undefined;
};

const minorOf = (version: string): string => version.split('.').slice(0, 2).join('.');

const collectSlots = (source: string): Set<string> => new Set(source.match(TAILWIND_SLOT) ?? []);

const readHostSlots = (tailwindRoot: string): Set<string> => {
  const distinct = new Set<string>();
  const dist = join(tailwindRoot, 'dist');
  for (const entry of readdirSync(dist)) {
    if (entry.endsWith('.mjs')) {
      for (const slot of collectSlots(readFileSync(join(dist, entry), 'utf-8'))) {
        distinct.add(slot);
      }
    }
  }
  return distinct;
};

/**
 * Every `--tw-` slot the design system deposits into must be one this app's Tailwind also
 * assembles, or the effect crosses the boundary into a slot nothing reads and silently
 * stops applying. The two builds are released independently and rarely land on the same
 * patch, so the vocabulary is compared directly; the version guard stops at the minor,
 * which is the granularity at which Tailwind adds or renames a slot.
 */
const assertInterchangeableSlots = (source: string, resolve: (id: string) => string): void => {
  const manifestPath = resolve('tailwindcss/package.json');
  const designSystemVersion = TAILWIND_BANNER.exec(source)?.[1];
  const hostVersion = readVersion(manifestPath);
  if (designSystemVersion === undefined || hostVersion === undefined
    || minorOf(designSystemVersion) !== minorOf(hostVersion)) {
    throw new Error(
      `Tailwind minor mismatch: the design system build reports ${designSystemVersion ?? 'none'}, `
      + `this app uses ${hostVersion ?? 'none'}. Reconcile them before regenerating, or the shared `
      + '`--tw-` slots stop being interchangeable.',
    );
  }

  const hostSlots = readHostSlots(dirname(manifestPath));
  const unknown = [...collectSlots(source)].filter((slot) => !hostSlots.has(slot));
  if (unknown.length > 0) {
    throw new Error(
      `The design system deposits into ${unknown.length} \`--tw-\` slot(s) this app's Tailwind `
      + `never assembles: ${unknown.join(', ')}.`,
    );
  }
};

const moduleRequire = createRequire(import.meta.url);
const sourcePath = moduleRequire.resolve('@filigran/design-system/dist/index.css');
const outputPath = join(import.meta.dirname, '..', 'src', 'styles', 'fds.css');

const source = readFileSync(sourcePath, 'utf-8');

assertInterchangeableSlots(source, moduleRequire.resolve);

const root = parse(source, { from: sourcePath });

root.walkDecls((declaration) => {
  if (declaration.prop.startsWith('--')) {
    declaration.prop = prefixName(declaration.prop);
  }
  declaration.value = prefixReferences(declaration.value);
});

root.walkAtRules('property', (atRule) => {
  atRule.params = prefixName(atRule.params.trim());
});

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${HEADER}${root.toString()}\n`, 'utf-8');

console.log(`Generated ${outputPath} from ${sourcePath}`);
