import { useNavbarCollapsed } from '@filigran/design-system';
import type { FunctionComponent, ReactNode } from 'react';
import { cn } from '../../../../utils';

/**
 * Row internals for `NavbarItem asChild` / `NavbarSubmenuItem asChild`: Radix `Slot` cannot inject
 * wrapper markup into an arbitrary child, so a router `Link` has to compose the icon and label spans
 * the design system renders itself in its non-`asChild` branch. Every class string below is copied
 * verbatim from `@filigran/design-system` at the currently installed version and must be re-checked
 * against `dist/components/navbar-item/NavbarItem.mjs` and
 * `dist/components/navbar-submenu/NavbarSubmenu.mjs` whenever that version moves. None of them is
 * generated by this app's own Tailwind build; they resolve only because `fds.css` carries the
 * design system's own compiled rules.
 */

interface NavbarRowContentProps {
  icon?: ReactNode,
  children: ReactNode,
}

export const NavbarRowContent: FunctionComponent<NavbarRowContentProps> = ({ icon, children }) => {
  const collapsed = useNavbarCollapsed();

  return (
    <>
      {icon && (
        <span
          className={cn(
            'inline-flex shrink-0',
            collapsed ? 'text-default-primary mr-0.5' : [
              'text-default-secondary',
              'group-hover:text-default-primary',
              'group-focus-visible:text-default-primary',
              'group-[[aria-current=page]]:text-default-primary',
            ],
            'group-data-[disabled]:text-default-disabled',
          )}
          aria-hidden="true"
        >
          {icon}
        </span>
      )}
      <span className={cn('flex-1 truncate text-left', collapsed && 'sr-only')}>{children}</span>
    </>
  );
};

export const NavbarSubmenuRowContent: FunctionComponent<NavbarRowContentProps> = ({ icon, children }) => (
  <>
    {icon && (
      <span
        className={cn(
          'inline-flex shrink-0',
          'text-default-secondary',
          'group-[[aria-current=page]]:text-filigran-brand-primary',
          'group-data-[disabled]:text-default-disabled',
        )}
        aria-hidden="true"
      >
        {icon}
      </span>
    )}
    <span className="flex-1 truncate text-left">{children}</span>
  </>
);
